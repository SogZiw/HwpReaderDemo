"""Build the reader-only @rhwp/core adapter from the pinned upstream files.

Usage: python3 tools/trim-rhwp.py INPUT_DIRECTORY OUTPUT_DIRECTORY --wasm-opt PATH
The optimizer must be Binaryen 132 (the npm binaryen 132.0.0 distribution works).
No source maps, samples or other reader assets are processed by this tool.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import tempfile


ROOT = Path(__file__).resolve().parents[1]
METHODS = {
    'DocumentExport': ['static __wrap', '__destroy_into_raw', 'free', 'contentLoss', 'hasBytes', 'takeBytes'],
    'HwpDocument': ['__destroy_into_raw', 'free', 'constructor', 'exportHwpxWithReport', 'getTextFileUnicode'],
}


def reader_bindings(source):
    # This is a transformation of one hash-pinned wasm-bindgen release, not a
    # general JS parser. Generated method bodies always indent by >= 8 spaces;
    # a line indented by exactly 4 spaces closes each method. Fail on drift.
    classes = []
    for name, methods in METHODS.items():
        match = re.search(r'^export class ' + name + r' \{\n(.*?)^\}', source, re.M | re.S)
        if not match:
            raise ValueError('Missing upstream class: ' + name)
        kept = []
        for method in methods:
            pattern = r'^    ' + re.escape(method) + r'\([^\n]*\) \{\n.*?^    \}\n'
            matches = list(re.finditer(pattern, match[1], re.M | re.S))
            if len(matches) != 1:
                raise ValueError('Unexpected upstream method: ' + name + '.' + method)
            kept.append(matches[0][0])
        classes.append('export class ' + name + ' {\n' + ''.join(kept) + '}\n'
                       + f'if (Symbol.dispose) {name}.prototype[Symbol.dispose] = {name}.prototype.free;\n')
    runtime = source[source.index('function __wbg_get_imports()'):]
    # Remove finalizers belonging to classes which are no longer exposed.
    for name in ['HwpViewer', 'PdfEditorReopen', 'PdfImportRequest']:
        runtime, count = re.subn(r'^const ' + name + r'Finalization = .*?;\n', '', runtime, flags=re.M | re.S)
        if count != 1:
            raise ValueError('Missing upstream finalizer: ' + name)
    return ('/* @rhwp/core 0.9.1, Copyright (c) 2025-2026 Edward Kim, MIT.\n'
            ' * Reader-only adapter: generated by tools/trim-rhwp.py.\n'
            ' * Keeps parsing, HWPX conversion, text extraction and conversion reports.\n'
            ' * See third_party/rhwp-core-LICENSE.txt and third_party/NOTICE.txt. */\n\n'
            + '\n'.join(classes) + '\n' + runtime)


def read_uleb(data, offset):
    value = shift = 0
    while True:
        byte = data[offset]
        offset += 1
        value |= (byte & 127) << shift
        if byte < 128:
            return value, offset
        shift += 7


def uleb(value):
    result = bytearray()
    while value >= 128:
        result.append((value & 127) | 128)
        value >>= 7
    result.append(value)
    return bytes(result)


def enabled_features(data):
    offset = 8
    while offset < len(data):
        kind = data[offset]
        size, start = read_uleb(data, offset + 1)
        end = start + size
        if kind == 0:
            length, cursor = read_uleb(data, start)
            if data[cursor:cursor + length] == b'target_features':
                count, cursor = read_uleb(data, cursor + length)
                features = set()
                for _ in range(count):
                    prefix = data[cursor]
                    length, cursor = read_uleb(data, cursor + 1)
                    if prefix == ord('+'):
                        features.add(data[cursor:cursor + length].decode())
                    cursor += length
                return features
        offset = end
    raise ValueError('Missing WASM target_features')


def prune_exports(data, keep):
    if data[:8] != b'\0asm\x01\0\0\0':
        raise ValueError('Invalid WASM header')
    output = bytearray(data[:8])
    offset = 8
    seen = set()
    removed = []
    while offset < len(data):
        kind = data[offset]
        size, start = read_uleb(data, offset + 1)
        end = start + size
        payload = data[start:end]
        if kind == 7:
            count, cursor = read_uleb(payload, 0)
            entries = []
            for _ in range(count):
                entry_start = cursor
                length, cursor = read_uleb(payload, cursor)
                name = payload[cursor:cursor + length].decode()
                cursor += length
                export_kind = payload[cursor]
                _, cursor = read_uleb(payload, cursor + 1)
                if export_kind != 0 or name in keep:
                    entries.append(payload[entry_start:cursor])
                    seen.add(name)
                else:
                    removed.append(name)
            if cursor != len(payload):
                raise ValueError('Invalid WASM export section')
            payload = uleb(len(entries)) + b''.join(entries)
        output += bytes([kind]) + uleb(len(payload)) + payload
        offset = end
    missing = keep - seen
    if missing:
        raise ValueError('Missing JS runtime exports: ' + ', '.join(sorted(missing)))
    return bytes(output), removed


def trim(input_dir, output_dir, wasm_opt, verify=True):
    lock = json.loads((ROOT / 'tools/vendor-lock.json').read_text())['rhwpCore']
    inputs = {name: (input_dir / name).read_bytes() for name in lock['files']}
    for name, expected in lock['files'].items():
        if hashlib.sha256(inputs[name]).hexdigest() != expected:
            raise ValueError('Upstream checksum mismatch: ' + name)
    version = subprocess.check_output([str(wasm_opt), '--version'], text=True).strip()
    if not re.search(r'\bversion 132\b', version):
        raise ValueError('Use pinned Binaryen 132, got: ' + version)
    bindings = reader_bindings(inputs['rhwp.js'].decode())
    keep = set(re.findall(r'\bwasm\.([A-Za-z0-9_]+)', bindings))
    pruned, removed = prune_exports(inputs['rhwp_bg.wasm'], keep)
    with tempfile.TemporaryDirectory(prefix='rhwp-reader-') as temporary:
        temporary = Path(temporary)
        source = temporary / 'pruned.wasm'
        target = temporary / 'rhwp_bg.wasm'
        source.write_bytes(pruned)
        # Preserve the input's target_features. -Oz performs global dead-code
        # elimination after removal of public editing/PDF/rendering roots.
        subprocess.run([str(wasm_opt), str(source), '-Oz', '--remove-unused-module-elements',
                        '--strip-producers', '-o', str(target)], check=True)
        outputs = {'rhwp.js': bindings.encode(), 'rhwp_bg.wasm': target.read_bytes()}
    allowed = enabled_features(inputs['rhwp_bg.wasm'])
    # Binaryen separately names the memory.copy/fill subset of bulk-memory.
    # An input already requiring bulk-memory supports both instructions.
    if 'bulk-memory' in allowed:
        allowed.add('bulk-memory-opt')
    if not enabled_features(outputs['rhwp_bg.wasm']) <= allowed:
        raise ValueError('Optimizer introduced a new WASM platform requirement')
    if verify:
        for name, expected in lock['readerOnly']['files'].items():
            if hashlib.sha256(outputs[name]).hexdigest() != expected:
                raise ValueError('Reader build is not reproducible: ' + name)
    output_dir.mkdir(parents=True, exist_ok=True)
    for name, data in outputs.items():
        (output_dir / name).write_bytes(data)
    return {'optimizer': version, 'removedExports': len(removed),
            'files': {name: {'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest()}
                      for name, data in outputs.items()}}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('input', type=Path)
    parser.add_argument('output', type=Path)
    parser.add_argument('--wasm-opt', type=Path, required=True)
    parser.add_argument('--update', action='store_true', help='Print new hashes instead of verifying output lock')
    args = parser.parse_args()
    print(json.dumps(trim(args.input, args.output, args.wasm_opt, not args.update), indent=2))
